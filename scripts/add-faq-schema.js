// ── Генерация JSON-LD ────────────────────────────────────────────────────────

function makeFaqSchema(faqs) {
  const schema = {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: faqs.map(f => ({
      '@type': 'Question',
      name: f.q,
      acceptedAnswer: { '@type': 'Answer', text: f.a },
    })),
  };
  return `<script type="application/ld+json">\n${JSON.stringify(schema, null, 2)}\n</script>`;
}

// ── Генерация HTML FAQ-секции ────────────────────────────────────────────────

function makeFaqHtml(heading, faqs) {
  const items = faqs.map(f => `
            <div class="law-faq-item">
              <button class="law-faq-question" aria-expanded="false">${f.q}<span class="law-faq-question-icon"><svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5"><line x1="12" y1="5" x2="12" y2="19"/><line x1="5" y1="12" x2="19" y2="12"/></svg></span></button>
              <div class="law-faq-answer"><p>${f.a}</p></div>
            </div>`).join('');

  return `
    <div class="law-faq mt-4">
      <h2 style="font-size:1.1rem;font-weight:800;margin-bottom:16px;color:#0f2044;">${heading}</h2>
${items}
    </div>`;
}

// ── Обработка файла ──────────────────────────────────────────────────────────

function processFile(filename, data) {
  const filePath = path.join(PUBLIC, filename);
  if (!fs.existsSync(filePath)) {
    console.log(`  ⚠️  Файл не найден: ${filename}`);
    return;
  }

  let html = fs.readFileSync(filePath, 'utf8');

  // Уже есть FAQPage схема?
  if (html.includes('"FAQPage"')) {
    console.log(`  ⏭  Уже есть FAQPage schema: ${filename}`);
    return;
  }

  // 1. Добавить JSON-LD перед </head>
  const schemaTag = makeFaqSchema(data.faqs);
  html = html.replace('</head>', `  ${schemaTag}\n</head>`);

  // 2. Если нужно добавить HTML-секцию FAQ
  if (data.addHtml) {
    const faqHtml = makeFaqHtml(data.heading || 'Частые вопросы', data.faqs);
    // Вставить перед </main> (или перед footer если нет </main>)
    if (html.includes('</main>')) {
      html = html.replace('</main>', `${faqHtml}\n</main>`);
    } else if (html.includes('<footer')) {
      html = html.replace('<footer', `${faqHtml}\n<footer`);
    }
  }

  fs.writeFileSync(filePath, html, 'utf8');
  console.log(`  ✅ Обновлён: ${filename}`);
}

