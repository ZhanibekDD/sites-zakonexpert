function makeFaqSchema(faqs) {
  return `<script type="application/ld+json">\n${JSON.stringify({
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: faqs.map(f => ({
      '@type': 'Question',
      name: f.q,
      acceptedAnswer: { '@type': 'Answer', text: f.a },
    })),
  }, null, 2)}\n</script>`;
}

function makeFaqHtml(heading, faqs) {
  const items = faqs.map(f => `
            <div class="law-faq-item">
              <button class="law-faq-question" aria-expanded="false">${f.q}<span class="law-faq-question-icon"><svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5"><line x1="12" y1="5" x2="12" y2="19"/><line x1="5" y1="12" x2="19" y2="12"/></svg></span></button>
              <div class="law-faq-answer"><p>${f.a}</p></div>
            </div>`).join('');
  return `\n    <div class="law-faq mt-4">\n      <h2 style="font-size:1.1rem;font-weight:800;margin-bottom:16px;color:#0f2044;">${heading}</h2>\n${items}\n    </div>`;
}

console.log('📋 Добавляем FAQPage schema на оставшиеся страницы...\n');

for (const [filename, data] of Object.entries(FAQ_DATA)) {
  const filePath = path.join(PUBLIC, filename);
  if (!fs.existsSync(filePath)) { console.log(`  ⚠️  Не найден: ${filename}`); continue; }

  let html = fs.readFileSync(filePath, 'utf8');
  if (html.includes('"FAQPage"')) { console.log(`  ⏭  Уже есть: ${filename}`); continue; }

  // JSON-LD в <head>
  html = html.replace('</head>', `  ${makeFaqSchema(data.faqs)}\n</head>`);

  // HTML секция перед </main> или <footer
  const faqHtml = makeFaqHtml(data.heading, data.faqs);
  if (html.includes('</main>')) {
    html = html.replace('</main>', `${faqHtml}\n</main>`);
  } else {
    html = html.replace('<footer', `${faqHtml}\n<footer`);
  }

  // FAQ JS если нет
  if (!html.includes('law-faq-question')) {
    html = html.replace('</body>', `<script>document.querySelectorAll('.law-faq-question').forEach(btn=>{btn.addEventListener('click',()=>{const item=btn.closest('.law-faq-item');const isOpen=item.classList.contains('open');document.querySelectorAll('.law-faq-item.open').forEach(i=>i.classList.remove('open'));if(!isOpen)item.classList.add('open');btn.setAttribute('aria-expanded',String(!isOpen));});});</script>\n</body>`);
  }

  fs.writeFileSync(filePath, html, 'utf8');
  console.log(`  ✅ ${filename}`);
}

console.log('\n✅ Готово!');
