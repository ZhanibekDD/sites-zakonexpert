'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');

function target(relativePath) {
  return path.join(ROOT, relativePath);
}

function read(relativePath) {
  return fs.readFileSync(target(relativePath), 'utf8');
}

function write(relativePath, content) {
  const current = read(relativePath);
  if (current === content) return;
  fs.writeFileSync(target(relativePath), content, 'utf8');
  console.log('updated', relativePath);
}

function replaceRequired(content, from, to, label, expectedMinimum = 1) {
  const count = content.split(from).length - 1;
  if (count < expectedMinimum) {
    throw new Error(`Expected at least ${expectedMinimum} occurrence(s) for ${label}, found ${count}`);
  }
  return content.split(from).join(to);
}

function replaceOptional(content, from, to) {
  return content.includes(from) ? content.split(from).join(to) : content;
}

function replaceRegexRequired(content, expression, replacement, label) {
  const matches = content.match(expression);
  if (!matches) throw new Error('Pattern not found: ' + label);
  return content.replace(expression, replacement);
}

function patch(relativePath, transform) {
  write(relativePath, transform(read(relativePath)));
}

