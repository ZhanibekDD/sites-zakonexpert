const INDEXABLE_LOCALES = Object.keys(LOCALES);

function getLocale(code) {
  return LOCALES[String(code || '').toLocaleLowerCase('en-US')] || LOCALES.ru;
}

function catalogPath(code) {
  return code === 'ru' ? '/companies' : `/${code}/companies`;
}

function companyPath(code, slug) {
  return code === 'ru' ? `/company/${slug}` : `/${code}/company/${slug}`;
}

function catalogAlternates() {
  const alternates = INDEXABLE_LOCALES.map(code => ({
    hreflang: LOCALES[code].hreflang,
    href: `https://zakonexpertt.kz${catalogPath(code)}`,
  }));
  alternates.push({ hreflang: 'x-default', href: 'https://zakonexpertt.kz/companies' });
  return alternates;
}

